def _names(n: int, taken: set[str]) -> list[str]:
    """성·이름을 섞어 겹치지 않는 이름 n개 (같은 팀 안에 같은 이름이 나오지 않게)."""
    out = []
    while len(out) < n:
        k = _seq["k"]
        _seq["k"] += 1
        full = _SUR[(k * 7 + k // len(_GIV)) % len(_SUR)] + _GIV[(k * 13) % len(_GIV)]
        if full in taken:
            continue
        taken.add(full)
        out.append(full)
    return out


def build() -> tuple[list[dict], list[dict]]:
    """(팀, 직원) — roster 에 붙일 확장 조직."""
    teams, agents = [], []
    _seq["k"] = 0
    taken = {a["name"] for a in roster.AGENTS}
    defs = [(tid, name, desc, color, kind, lead, specs, None) for tid, name, desc, color, kind, lead, specs in FUNCTIONAL]
    defs += [(f"coin_{sym[:-4].lower()}", f"{ko}팀", f"{ko}({sym}) 한 코인만 깊게 분석한다", color, "coinx", f"{ko}팀장", COIN_SPECS, sym)
             for sym, ko, color in COINS]
    for k, (tid, name, desc, color, kind, lead, specs, sym) in enumerate(defs):
        teams.append({"id": tid, "name": name, "desc": desc, "color": color, "kind": kind, "symbol": sym, "ext": True})
        names = _names(11, taken)
        for j in range(11):
            spec = None if j == 0 else specs[j - 1]
            title = lead if j == 0 else f"{spec} 담당"
            duty = (f"{name}을 이끈다. 팀원들의 분석을 모아 결론과 다음 할 일을 정하고, 팀의 판정 기준을 지킨다."
                    if j == 0 else f"{name}에서 '{spec}'를 전담한다. 이 관점의 근거만 보고 판단하며, 데이터에 없는 숫자는 지어내지 않는다.")
            agents.append({"id": f"{tid}_{j}", "name": names[j], "team": tid, "title": title, "role": "reason" if kind in ("bt", "live", "dev", "cdev") and j < 3 else "general",
                           "skills": SKILLS.get(kind, ["crypto_futures"]), "look": [_LOOK_H[(k + j) % len(_LOOK_H)], color], "long": (k + j) % 3 == 0, "duty": duty, "lead": j == 0,
                           "spec": spec, "ext": True})
    return teams, agents


def install() -> None:
    """roster 에 확장 조직을 붙인다 (한 번만)."""
    if any(t.get("ext") for t in roster.TEAMS):
        return
    teams, agents = build()
    roster.TEAMS.extend(teams)
    roster.AGENTS.extend(agents)
    for t in teams:
        roster.TEAM_BY[t["id"]] = t
        roster.MEMBERS[t["id"]] = [a["id"] for a in agents if a["team"] == t["id"]]
        roster.TEAM_LEAD[t["id"]] = f"{t['id']}_0"
        roster.IDLE[t["id"]] = [f"📊 {t['name']} 자료 보는 중", "📝 분석 노트 정리 중"]
    for a in agents:
        roster.BY_ID[a["id"]] = a
        t = roster.TEAM_BY[a["team"]]
        sym = t.get("symbol") or "BTCUSDT"
        kind = t["kind"]
        roster.WATCH[a["id"]] = {"ind": [("indicators", sym)], "trend": [("indicators", sym)], "entry": [("book", sym)], "news": [("news", "crypto")],
                                 "sr": [("book", sym)], "tpsl": [("paper", "")], "board": [("movers", "")], "pattern": [("indicators", sym)],
                                 "coinx": [("quote", sym), ("whale", sym), ("news", "crypto")], "termind": [("termind", "")], "dev": [("research", "")], "cdev": [("research", "")],
                                 "bt": [("research", "")], "demo": [("paper", "")], "live": [("paper", "")]}.get(kind, [("quote", sym)])
        mates = roster.MEMBERS[a["team"]]
        i = mates.index(a["id"])
        roster.RELATED[a["id"]] = [mates[(i + 1) % len(mates)], mates[(i + 2) % len(mates)], mates[0] if i else mates[3]]


